//! Fetch (3D) label colour.

use anyhow::Result;

use crate::color::{Mode, Role};
use crate::context::{Report, ThemeContext};
use crate::targets::Target;

pub struct FetchTarget;

impl Target for FetchTarget {
    fn id(&self) -> &'static str {
        "fetch3d"
    }
    fn label(&self) -> &'static str {
        "Fetch 3D (not fastfetch)"
    }
    fn description(&self) -> &'static str {
        "Set 3D fetch label_color to the iNiR accent, 10% darker"
    }

    fn apply(&self, ctx: &ThemeContext) -> Result<Report> {
        let mut report = Report::new(self.id());
        let path = ctx.home.join(".config/fetch/config");
        let old = std::fs::read_to_string(&path).unwrap_or_default();
        let bg = ctx.palette.background;
        let color = ctx.accent().adjust(
            ctx.options.fetch_darken,
            0.0,
            Role::Accent,
            Some(bg),
            Mode::Readable,
        );
        let line = format!("label_color={}", color.to_sgr());
        let new = if let Some(pos) = old
            .lines()
            .position(|l| l.trim_start().starts_with("label_color="))
        {
            let mut lines: Vec<String> = old.lines().map(str::to_string).collect();
            lines[pos] = line;
            let mut out = lines.join("\n");
            out.push('\n');
            out
        } else if old.trim().is_empty() {
            format!("# generated by inir-theme\n{line}\n")
        } else {
            let mut out = old.trim_end().to_string();
            out.push('\n');
            out.push_str(&line);
            out.push('\n');
            out
        };
        if ctx.write(&path, &new, &mut report)? {
            report
                .notes
                .push(format!("label_color -> {}", color.to_hex()));
        }
        report
            .notes
            .push("icons need the patched fetch-3d (patches/fetch-icons-dark-label.patch)".into());
        Ok(report)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::Palette;

    #[test]
    fn updates_label_color() {
        let dir = tempfile::tempdir().unwrap();
        let cfg = dir.path().join(".config/fetch/config");
        std::fs::create_dir_all(cfg.parent().unwrap()).unwrap();
        std::fs::write(&cfg, "os\nlabel_color=35\nheight=20\n").unwrap();
        let kitty = dir.path().join("theme.conf");
        std::fs::write(
            &kitty,
            "background #1c1e19\nforeground #c6c6be\nactive_border_color #b78cda\n",
        )
        .unwrap();
        let mut ctx = ThemeContext::new(Palette::from_kitty(&kitty).unwrap());
        ctx.home = dir.path().to_path_buf();
        ctx.reload = false;
        FetchTarget.apply(&ctx).unwrap();
        let out = std::fs::read_to_string(&cfg).unwrap();
        assert!(out.contains("label_color=38;2;"));
        assert!(out.contains("height=20"));
    }
}

//! Herdr: write `[theme.custom]` and reload the running server.

use std::collections::BTreeMap;
use std::process::Command;

use anyhow::Result;

use crate::color::{Color, Mode, Role};
use crate::context::{Report, ThemeContext};
use crate::targets::Target;

pub struct HerdrTarget;

impl Target for HerdrTarget {
    fn id(&self) -> &'static str {
        "herdr"
    }
    fn label(&self) -> &'static str {
        "Herdr"
    }
    fn description(&self) -> &'static str {
        "Herdr UI palette: exact iNiR accent, darker surfaces and ANSI colours"
    }

    fn apply(&self, ctx: &ThemeContext) -> Result<Report> {
        let mut report = Report::new(self.id());
        let path = ctx.home.join(".config/herdr/config.toml");
        let palette = build_palette(ctx);
        let text = std::fs::read_to_string(&path).unwrap_or_default();
        let new = replace_custom_block(&text, &palette);
        if ctx.write(&path, &new, &mut report)? {
            report.notes.push(if ctx.dry_run {
                "would update [theme.custom]".into()
            } else {
                "updated [theme.custom]".into()
            });
        }
        if ctx.reload && !ctx.dry_run {
            reload(&mut report);
        }
        Ok(report)
    }
}

fn build_palette(ctx: &ThemeContext) -> BTreeMap<&'static str, Color> {
    let p = &ctx.palette;
    let darken = ctx.options.herdr_darken;
    let sat = ctx.options.herdr_saturate;
    let bg = p
        .background
        .adjust(darken, sat, Role::Background, None, Mode::Readable);
    let container =
        p.surface_container_high
            .adjust(darken, sat, Role::Background, Some(bg), Mode::Readable);
    let selection =
        p.selection_background
            .adjust(darken, sat, Role::Muted, Some(bg), Mode::Readable);
    let text = p
        .foreground
        .adjust(darken, sat, Role::Text, Some(bg), Mode::Readable);
    let subtext = p
        .on_surface_variant
        .adjust(darken, sat, Role::Text, Some(bg), Mode::Readable);
    let overlay0 = p
        .outline
        .adjust(darken, sat, Role::Muted, Some(bg), Mode::Readable);
    let overlay1 = p
        .on_surface_variant
        .adjust(darken, sat, Role::Muted, Some(bg), Mode::Readable);
    let accent = ctx.accent();
    let t = |i: usize| {
        p.terminal(i)
            .adjust(darken, sat, Role::Accent, Some(bg), Mode::Readable)
    };

    BTreeMap::from([
        ("accent", accent),
        ("panel_bg", bg),
        ("sidebar_bg", bg),
        ("active_row_bg", container),
        ("selection_bg", selection),
        ("surface0", container),
        ("surface1", selection),
        ("surface_dim", bg),
        ("overlay0", overlay0),
        ("overlay1", overlay1),
        ("text", text),
        ("subtext0", subtext),
        ("mauve", t(5)),
        ("green", t(2)),
        ("yellow", t(3)),
        ("red", t(1)),
        ("blue", t(4)),
        ("teal", t(6)),
        ("peach", t(11)),
    ])
}

fn replace_custom_block(text: &str, palette: &BTreeMap<&'static str, Color>) -> String {
    let mut lines: Vec<String> = text.lines().map(str::to_string).collect();
    let mut block = vec![
        "[theme.custom]".to_string(),
        "# generated by inir-theme (Rust)".to_string(),
    ];
    block.extend(
        palette
            .iter()
            .map(|(key, value)| format!("{key} = \"{}\"", value.to_hex())),
    );

    if let Some(start) = lines.iter().position(|l| l.trim() == "[theme.custom]") {
        let mut end = lines.len();
        for (i, line) in lines.iter().enumerate().skip(start + 1) {
            if line.trim_start().starts_with('[') {
                end = i;
                break;
            }
        }
        let mut replacement = block;
        if end < lines.len() {
            replacement.push(String::new());
        }
        lines.splice(start..end, replacement);
    } else {
        if lines.last().map(|l| !l.trim().is_empty()).unwrap_or(false) {
            lines.push(String::new());
        }
        lines.extend(block);
    }
    let mut out = lines.join("\n");
    out.push('\n');
    out
}

fn reload(report: &mut Report) {
    for args in [vec!["config", "check"], vec!["server", "reload-config"]] {
        match Command::new("herdr").args(&args).output() {
            Ok(out) if out.status.success() => {}
            Ok(out) => report.notes.push(format!(
                "herdr {} failed: {}",
                args.join(" "),
                String::from_utf8_lossy(&out.stderr).trim()
            )),
            Err(err) => {
                report
                    .notes
                    .push(format!("herdr {} not run: {err}", args.join(" ")));
                return;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::Palette;

    #[test]
    fn writes_accent_and_keeps_other_sections() {
        let dir = tempfile::tempdir().unwrap();
        let cfg = dir.path().join(".config/herdr/config.toml");
        std::fs::create_dir_all(cfg.parent().unwrap()).unwrap();
        std::fs::write(
            &cfg,
            "onboarding = false\n\n[theme]\nname = \"vesper\"\n\n[theme.custom]\naccent = \"#111111\"\n\n[terminal]\ndefault_shell = \"zsh\"\n",
        )
        .unwrap();

        let palette = Palette::from_kitty(&write_kitty(dir.path())).unwrap();
        let mut ctx = ThemeContext::new(palette);
        ctx.home = dir.path().to_path_buf();
        ctx.reload = false;
        HerdrTarget.apply(&ctx).unwrap();

        let out = std::fs::read_to_string(&cfg).unwrap();
        assert!(out.contains("accent = \"#35b28f\""));
        assert!(out.contains("[terminal]"));
        assert!(out.contains("default_shell = \"zsh\""));
    }

    fn write_kitty(dir: &std::path::Path) -> std::path::PathBuf {
        let p = dir.join("theme.conf");
        std::fs::write(
            &p,
            "background #1c1e19\nforeground #c6c6be\nactive_border_color #35b28f\ncolor0 #1c1e19\ncolor1 #ff0000\ncolor2 #00ff00\ncolor3 #ffff00\ncolor4 #0000ff\ncolor5 #ff00ff\ncolor6 #00ffff\ncolor7 #cccccc\ncolor8 #888888\ncolor9 #ff9999\ncolor10 #99ff99\ncolor11 #ffff99\ncolor12 #9999ff\ncolor13 #ff99ff\ncolor14 #99ffff\ncolor15 #ffffff\n",
        )
        .unwrap();
        p
    }
}

//! Cmatrix/lavat launcher wrappers using the current palette.

use std::os::unix::fs::PermissionsExt;

use anyhow::Result;

use crate::context::{Report, ThemeContext};
use crate::targets::Target;

pub struct LaunchersTarget;

impl Target for LaunchersTarget {
    fn id(&self) -> &'static str {
        "launchers"
    }
    fn label(&self) -> &'static str {
        "cmatrix / lavat"
    }
    fn description(&self) -> &'static str {
        "Write cmx/lavax wrappers with the current accent"
    }

    fn apply(&self, ctx: &ThemeContext) -> Result<Report> {
        let mut report = Report::new(self.id());
        let accent = ctx.accent();
        let teal = ctx.palette.terminal(6);
        let cmatrix_color = accent.nearest_ansi_name();
        let cmx = format!(
            "#!/bin/sh\n# generated by ginir-theme\nexec cmatrix -C {cmatrix_color} -u 2 -c \"$@\"\n"
        );
        let lavax = format!(
            "#!/bin/sh\n# generated by ginir-theme\nexec lavat -g -c {accent} -k {teal} -G -b 12 -r 6 -R 2 \"$@\"\n",
            accent = accent.to_hex_bare(),
            teal = teal.to_hex_bare(),
        );
        for (name, body) in [("cmx", cmx), ("lavax", lavax)] {
            let path = ctx.home.join(".local/bin").join(name);
            if ctx.write(&path, &body, &mut report)? {
                report.notes.push(format!(
                    "{} {}",
                    if ctx.dry_run { "would write" } else { "wrote" },
                    path.display()
                ));
            }
            if !ctx.dry_run {
                if let Ok(meta) = std::fs::metadata(&path) {
                    let mut perms = meta.permissions();
                    perms.set_mode(0o755);
                    let _ = std::fs::set_permissions(&path, perms);
                }
            }
        }
        report
            .notes
            .push(format!("cmatrix colour: {cmatrix_color}"));
        Ok(report)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::Palette;

    #[test]
    fn writes_wrappers() {
        let dir = tempfile::tempdir().unwrap();
        let kitty = dir.path().join("theme.conf");
        std::fs::write(
            &kitty,
            "background #1c1e19\nforeground #c6c6be\nactive_border_color #b78cda\ncolor6 #00ffff\n",
        )
        .unwrap();
        let mut ctx = ThemeContext::new(Palette::from_kitty(&kitty).unwrap());
        ctx.home = dir.path().to_path_buf();
        ctx.reload = false;
        LaunchersTarget.apply(&ctx).unwrap();
        assert!(dir.path().join(".local/bin/cmx").exists());
        assert!(dir.path().join(".local/bin/lavax").exists());
    }
}
